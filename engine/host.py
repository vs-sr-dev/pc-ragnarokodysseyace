def cmd_stage(tree, stage='010_01_01', quest='q00101',
              json_path='job.cpk/sw/sw.json', gait='run', limit=3000) -> int:
    """Milestone 2: a stage runs.

    The stage's script initialises it, a body with the game's own parameters
    walks it, the trigger volumes fire the functions their own `trigger.trg`
    names, and a `cfMapJump` loads the next stage and starts it too."""
    host = Host(tree, quest=quest)
    host.load_common()
    host.enter_stage(stage)
    params = load_params(host.tree / json_path)

    m = host.world.marker('appear01')
    act = Actor(params, m.position[0], m.position[1], m.position[2],
                m.rotation[1])
    goal = _exit_of(host.world)
    host.note('walk', 'from appear01 towards %s, %.1f m away'
              % (goal.name, math.hypot(m.position[0] - goal.position[0],
                                       m.position[2] - goal.position[2])))
    inside_now = set()
    stages = [stage]
    off_mesh = 0
    for _ in range(limit):
        host.frame += 1
        host.tick_threads()
        head = bearing(act.x, act.z, goal.position[0], goal.position[2])
        r = act.step(host.world, gait=gait, facing=head)
        if r['event'].startswith('off'):
            off_mesh += 1
        now = {t.name: t for t in host.triggers_at(act.x, act.y, act.z)}
        for name, t in now.items():
            if name in inside_now:
                continue
            if t.kind in (0, 1):
                host.note('trigger', 'entered %s: %s' % (name, t.script))
                host.run_source(t.script)
        for name in list(inside_now):
            if name not in now:
                t = next((x for x in host.world.stage.triggers
                          if x.name == name), None)
                if t is not None and t.kind == 2:
                    host.note('trigger', 'left %s: %s' % (name, t.script))
                    host.run_source(t.script)
        inside_now = set(now)
        if host.pending_jump:
            nxt, arrive = host.pending_jump
            host.pending_jump = None
            if not (host.tree / 'stage.cpk' / nxt / 'param.pac').is_dir():
                host.note('jump', '%s is not on the disc - stopping' % nxt)
                break
            host.enter_stage(nxt, arrive)
            stages.append(nxt)
            m = host.world.marker(arrive)
            act = Actor(params, m.position[0], m.position[1], m.position[2],
                        m.rotation[1])
            goal = _exit_of(host.world)
            inside_now = set()
            host.note('walk', 'from %s towards %s' % (arrive, goal.name))
            if len(stages) >= 2:
                break                           # one jump is the milestone
    fired = sum(1 for f, k, t in host.events if k == 'trigger')
    volumes = sum(1 for t in host.world.stage.triggers)
    print()
    print('  %d frames = %.2f s, %d stages: %s'
          % (host.frame, host.frame / FPS, len(stages), ' -> '.join(stages)))
    print('  %d scripts loaded: %s'
          % (len(host.loaded),
             ', '.join(p.rsplit('/', 1)[-1] for p in host.loaded)))
    print('  %d instructions retired, %d host calls, %d trigger volumes on '
          'the last stage and %d fired'
          % (host.steps,
             sum(host.real_calls.values()) + sum(host.stub_calls.values()),
             volumes, fired))
    reached = set(host.real_calls) | set(host.stub_calls)
    print('  %d of the 285 reached: %d that do something, %d recorded as '
          'stubs' % (len(reached & set(NATIVES)),
                     len(set(host.real_calls) & set(NATIVES)),
                     len(set(host.stub_calls) & set(NATIVES))))
    print('  %d frames with no ground underneath' % off_mesh)
    if host.missing:
        print('  %d names called that nothing loaded defines: %s'
              % (len(host.missing), ', '.join(sorted(host.missing))))
    if host.threads:
        print('  %d threads still inside a suspend: %s'
              % (len(host.threads), ', '.join(t[4] for t in host.threads)))
    return 0


def _exit_of(world):
    for m in world.stage.markers:
        if m.kind.startswith('jump_'):
            return m
    return world.stage.markers[0]


def demo_length(pac):
    """A cutscene's length in frames, off its own camera track."""
    for c in sorted(pathlib.Path(pac).glob('*.CSCM')):
        b = c.read_bytes()
        if b[:4] == b'CSCM' and len(b) > CSCM_FRAMES + 2:
            return int.from_bytes(b[CSCM_FRAMES:CSCM_FRAMES + 2], 'big')
    return None


def run_demo(host, rel, frames, over=120):
    """The cutscene protocol: `demoInitBGM`, `demoInit`, then `demoUpdate`
    once a frame until the script says `setDemoEnd`, then `demoEnd`."""
    host.demo = {'on': True, 'frame': 0, 'end': frames}
    host.load_script(rel)
    for fn in ('demoInitBGM', 'demoInit'):
        host.call(fn, why=fn)
    ended = None
    for f in range(frames + over):
        host.frame = f
        host.demo['frame'] = f
        host.tick_threads()
        host.call('demoUpdate', why='demoUpdate')
        if host.demo.get('ended'):
            ended = f
            break
    host.call('demoEnd', why='demoEnd')
    return ended


def cmd_demo(tree, want='*', verbose='1') -> int:
    """Run a cutscene script against its own camera track.

    The check is behavioural and it is the sharpest one here: a cutscene
    script is a phase machine that counts frames, and driving it with the
    length its own `.CSCM` declares either brings it to `setDemoEnd` or does
    not. Nothing about that is arranged - the script's thresholds are the
    author's and the length is the camera track's."""
    root = pathlib.Path(tree) / 'demo.cpk'
    pacs = sorted(p for p in root.iterdir() if p.is_dir())
    ran = ended = nolength = 0
    late = []
    one = not fnmatch_all(want)
    for pac in pacs:
        if not fnmatch.fnmatch(pac.name, want if want.endswith('.pac')
                               else want + '.pac'):
            continue
        psq = [q for q in pac.glob('*.psq')]
        if not psq:
            continue
        frames = demo_length(pac)
        if frames is None:
            nolength += 1
            continue
        host = Host(tree, verbose=(one and verbose != '0'))
        host.load_common()
        rel = psq[0].relative_to(pathlib.Path(tree)).as_posix()
        try:
            at = run_demo(host, rel, frames)
        except (SquirrelError, VMError) as e:
            print('  %-28s %s' % (pac.name, e))
            continue
        ran += 1
        if at is not None:
            ended += 1
            late.append((at - frames, pac.name, at, frames))
        if one:
            print()
            print('  %s: %d frames of camera track, the script ended at %s'
                  % (pac.name, frames, at if at is not None else 'no end'))
            print('  %d instructions retired, %d host calls'
                  % (host.steps, sum(host.real_calls.values())
                     + sum(host.stub_calls.values())))
            reached = (set(host.real_calls) | set(host.stub_calls))                 & set(NATIVES)
            print('  %d of the 285 reached: %s'
                  % (len(reached), ', '.join(sorted(reached))))
    if not one:
        print('%d cutscenes driven by their own camera track, %d reached '
              'setDemoEnd, %d have no track' % (ran, ended, nolength))
        late.sort()
        for d, name, at, frames in late[:3] + late[-3:]:
            print('  %-28s ended at %4d of %4d' % (name, at, frames))
    return 0


def fnmatch_all(want):
    return want in ('*', '')


def cmd_talk(tree, script, func='', stage='140_02_01') -> int:
    """Run one conversation, and print it.

    This is the `suspend` protocol end to end: `talk(speaker, message)` is
    `cfTalk(...); suspend(101)`, so the script stops on every line and the
    host resumes it a frame later. The text comes from the two tables
    [`format_api.md`](../docs/format_api.md) joins the arguments to."""
    host = Host(tree, quest='')
    host.load_common()
    host.enter_stage(stage)
    rel = script if '/' in script else None
    if rel is None:
        found = list((pathlib.Path(tree)).rglob(script))
        if not found:
            raise SystemExit('no script named ' + script)
        rel = found[0].relative_to(pathlib.Path(tree)).as_posix()
    host.load_script(rel)
    name = func or rel.rsplit('/', 1)[-1].rsplit('.', 1)[0]
    host.note('talk', 'calling %s()' % name)
    host.call(name, why=name)
    while host.threads and host.frame < 20000:
        host.frame += 1
        host.tick_threads()
    lines = sum(1 for f, k, t in host.events if k == 'talk')
    print()
    print('  %d frames, %d instructions retired, %d host calls'
          % (host.frame, host.steps,
             sum(host.real_calls.values()) + sum(host.stub_calls.values())))
    print('  %d lines of conversation, %d threads still waiting'
          % (lines, len(host.threads)))
    reached = (set(host.real_calls) | set(host.stub_calls)) & set(NATIVES)
    print('  %d of the 285 reached: %s'
          % (len(reached), ', '.join(sorted(reached))))
    return 0


def cmd_stages(tree, want='*') -> int:
    """Load every stage's world and script and call `sfStageInit`."""
    root = pathlib.Path(tree) / 'stage.cpk'
    names = sorted(p.name for p in root.iterdir()
                   if (p / 'param.pac').is_dir())
    ok = withscript = failed = clash = 0
    trig = readable = 0
    unbound = {}
    for name in names:
        if not pathlib.Path(tree).joinpath(
                'stage.cpk', name, 'param.pac', 'hta.bin').is_file():
            continue
        host = Host(tree, verbose=False)
        try:
            host.load_common()
            host.enter_stage(name)
        except (SquirrelError, VMError, SystemExit, ValueError) as e:
            failed += 1
            print('  %-12s %s' % (name, e))
            continue
        ok += 1
        withscript += any('/%s.psq' % name in p for p in host.loaded)
        for t in host.world.stage.triggers:
            trig += 1
            readable += call_line(t.script) is not None
        for n in host.missing:
            unbound[n] = unbound.get(n, 0) + 1
        clash += len(host.vm.collisions)
    print('%d stages: %d loaded and initialised, %d with a script of their '
          'own, %d failed' % (len(names), ok, withscript, failed))
    print('%d trigger lines, %d of them read as calls with constant '
          'arguments' % (trig, readable))
    print('%d names defined twice over a stage and the resident library'
          % clash)
    print('%d names called that nothing binds%s'
          % (len(unbound), ': ' + ', '.join(sorted(unbound)) if unbound
             else ''))
    return 1 if failed else 0


def cmd_api(tree) -> int:
    """The interface, and how much of it this file answers."""
    host = Host(tree, verbose=False)
    bound = [n for n in NATIVES if n in host.vm.root.slots]
    real = sorted(set(host.implemented) & set(NATIVES))
    print('%d functions in the interface, %d bound, %d of them doing '
          'something' % (len(NATIVES), len(bound), len(real)))
    print('%d calls a run of the whole disc would make through the %d that '
          'do something, of %d in total'
          % (sum(NATIVES[n] for n in real), len(real),
             sum(NATIVES.values())))
    for n in real:
        print('  %6d  %s' % (NATIVES[n], n))
    missing = sorted(set(NATIVES) - set(bound))
    if missing:
        print('not bound: %s' % ', '.join(missing))
    return 0


def main() -> int:
    a = sys.argv[1:]
    if not a:
        print(__doc__)
        return 2
    cmd, rest = a[0], a[1:]
    if cmd == 'stage' and rest:
        return cmd_stage(*rest)
    if cmd == 'demo' and rest:
        return cmd_demo(*rest)
    if cmd == 'talk' and len(rest) >= 2:
        return cmd_talk(*rest)
    if cmd == 'stages' and rest:
        return cmd_stages(*rest)
    if cmd == 'api' and rest:
        return cmd_api(*rest)
    print(__doc__)
    return 2


if __name__ == '__main__':
    raise SystemExit(main())
