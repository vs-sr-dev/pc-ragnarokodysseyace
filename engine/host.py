    def enter_stage(self, name, marker='appear01'):
        """Load a stage's world and its scripts, and call `sfStageInit`."""
        d = self.tree / 'stage.cpk' / name / 'param.pac'
        if not d.is_dir():
            raise SystemExit('no stage %s under %s' % (name, self.tree))
        self.world = World(d)
        self.stage_name = name
        self.characters.clear()
        self.hit_areas = {m.name: True for m in self.world.stage.markers}
        if self.spawner is not None:
            self.spawner.enter(name, self.world)
        self.note('stage', 'entered %s at %s (%d markers, %d triggers)'
                  % (name, marker, len(self.world.stage.markers),
                     len(self.world.stage.triggers)))
        # A stage's own `param.pac` may ship more than one script - the
        # town ships its NPC layer beside its stage layer - and both are
        # resident. Its *conversations* are not: the 460 scripts under
        # `140_02_01` collide on 147 names, seventeen of them defining
        # `talkNornThanks`, so the host loads one when a conversation starts.
        for q in sorted((d).glob('*.psq')):
            self.load_script('stage.cpk/%s/param.pac/%s' % (name, q.name))
        if self.quest:
            self.load_script('quest.cpk/%s.pac/%s.psq' % (self.quest, name))
        for fn in ('sfStageInit', 'sfQuestInit'):
            self.call(fn, why=fn)
        return self.world

    # -- running scripts ---------------------------------------------------

    def call(self, name, args=(), why=''):
        """Call a script function, and keep the thread if it suspends."""
        fn = self.vm.find(name)
        if not isinstance(fn, Closure):
            return None
        th = Thread(self.vm, name)
        try:
            th.start(fn, list(args))
        except SquirrelError as e:
            self.note('error', '%s: %s' % (name, e))
            return th
        self.steps += th.steps
        if th.state == 'suspended':
            self._park(th, why or name)
        return th

    def run_source(self, text):
        """Run a line of trigger source: a sequence of calls."""
        calls = call_line(to_string(text))
        if calls is None:
            self.note('error', 'cannot read trigger source %r' % text)
            return 0
        for name, args in calls:
            fn = self.vm.find(name)
            if fn is None:
                self.note('error', 'the trigger calls %s, which nothing '
                                   'defines' % name)
                continue
            if isinstance(fn, Native):
                fn.fn(*args)
                continue
            self.call(name, args, why='trigger %s' % name)
        return 0

    def _park(self, th, why):
        n = self.value_of_suspend(th.value)
        delay, value, what = n
        wake = self.frame + (self.wait_count if delay == 'wait' else delay)
        self.threads.append([th, wake, value, what, why])
        self.note('suspend', '%s waits on %s (%s), %d frames'
                  % (why, to_string(th.value), what,
                     max(0, wake - self.frame)))

    def value_of_suspend(self, n):
        if isinstance(n, int) and n in RESUME:
            return RESUME[n]
        return (0, None, 'unknown suspend %s' % to_string(n))

    def tick_threads(self):
        for row in list(self.threads):
            th, wake, value, what, why = row
            if self.frame < wake:
                continue
            self.threads.remove(row)
            before = th.steps
            try:
                th.resume(value)
                self.steps += th.steps - before
            except SquirrelError as e:
                self.note('error', '%s: %s' % (why, e))
                continue
            if th.state == 'suspended':
                self._park(th, why)

    # -- the frame ---------------------------------------------------------

    def triggers_at(self, x, y, z):
        """Which trigger volumes contain a point, of the ones still on."""
        out = []
        by_name = self.world.stage.atih.by_name()
        for t in self.world.stage.triggers:
            m = by_name.get(t.name)
            if m is None or not m.volume:
                continue
            if not self.hit_areas.get(t.name, True):
                continue
            if inside(m, x, y, z):
                out.append(t)
        return out


