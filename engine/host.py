# -- the trigger language --------------------------------------------------

NAME = re.compile(r'\s*([A-Za-z_]\w*)\s*\(')


def call_line(text: str):
    """`MapJumpA(); callQuestScript("sfEnmGenStart()");` as (name, args).

    A trigger's script field is Squirrel source with constant arguments and
    nothing else - no operators, no locals - on all 508 triggers the disc
    ships. The argument may itself be a line of source in a string, which is
    why the closing bracket has to be found with the quotes respected and not
    with a regular expression: 147 of the 508 are
    `callQuestScript("<something>()")` and a lazy bracket match reads them as
    ending inside the string.

    Anything richer than a call with constant arguments belongs in the VM,
    and this returns None for it rather than guessing."""
    out, pos = [], 0
    while pos < len(text):
        if not text[pos:].strip():
            break
        m = NAME.match(text, pos)
        if not m:
            return None
        end = _closing(text, m.end() - 1)
        if end is None:
            return None
        args = []
        for a in _split_args(text[m.end():end]):
            v = _literal(a)
            if v is _BAD:
                return None
            args.append(v)
        out.append((m.group(1), args))
        pos = end + 1
        while pos < len(text) and text[pos] in ' \t\r\n;':
            pos += 1
    return out


def _closing(text, open_at):
    """The `)` that matches the `(` at `open_at`, ignoring brackets inside
    string literals."""
    depth, quote = 0, ''
    for i in range(open_at, len(text)):
        c = text[i]
        if quote:
            if c == quote:
                quote = ''
            continue
        if c in '"\'':
            quote = c
        elif c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                return i
    return None


_BAD = object()


def _split_args(s: str):
    out, depth, cur, quote = [], 0, '', ''
    for c in s:
        if quote:
            cur += c
            if c == quote:
                quote = ''
            continue
        if c in '"\'':
            quote = c
            cur += c
        elif c == '(':
            depth += 1
            cur += c
        elif c == ')':
            depth -= 1
            cur += c
        elif c == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    if cur.strip():
        out.append(cur)
    return [a.strip() for a in out if a.strip()]


def _literal(a: str):
    if len(a) >= 2 and a[0] == a[-1] and a[0] in '"\'':
        return a[1:-1]
    try:
        return int(a, 0)
    except ValueError:
        pass
    try:
        return float(a)
    except ValueError:
        return _BAD


def _arity(fn):
    """How many positional arguments a binding takes, at least and at most."""
    if fn is None:
        return 0, 0
    try:
        sig = inspect.signature(fn)
    except (TypeError, ValueError):
        return 0, 99
    lo = hi = 0
    for p in sig.parameters.values():
        if p.kind in (p.VAR_POSITIONAL, p.VAR_KEYWORD):
            return lo, 99
        if p.kind in (p.POSITIONAL_ONLY, p.POSITIONAL_OR_KEYWORD):
            hi += 1
            if p.default is p.empty:
                lo += 1
    return lo, hi


# -- geometry --------------------------------------------------------------


def inside(marker, x, y, z) -> bool:
    """Is a point inside a marker's oriented box? The rotation is a triple
    but only the Y of it turns a footprint, and 1,432 markers stand upright."""
    dx, dy, dz = x - marker.position[0], y - marker.position[1], \
        z - marker.position[2]
    a = math.radians(marker.rotation[1])
    ca, sa = math.cos(a), math.sin(a)
    lx = dx * ca - dz * sa
    lz = dx * sa + dz * ca
    ex, ey, ez = marker.extents
    return abs(lx) <= ex and abs(lz) <= ez and abs(dy) <= max(ey, 2.0)


